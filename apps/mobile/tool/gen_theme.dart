// Turns docs/brand/tokens.json into lib/core/ui/tokens.g.dart.
// Run from apps/mobile:  dart run tool/gen_theme.dart
import 'dart:convert';
import 'dart:io';

String _hex(String v) {
  final s = v.trim();
  if (s.startsWith('#')) {
    final h = s.substring(1);
    final full = h.length == 6 ? 'FF$h' : h;
    return '0x${full.toUpperCase()}';
  }
  final m = RegExp(r'rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)').firstMatch(s);
  if (m == null) throw FormatException('Unsupported colour: $v');
  final a = (double.parse(m.group(4)!) * 255).round();
  String two(int n) => n.toRadixString(16).padLeft(2, '0').toUpperCase();
  return '0x${two(a)}${two(int.parse(m.group(1)!))}'
      '${two(int.parse(m.group(2)!))}${two(int.parse(m.group(3)!))}';
}

void main() {
  final file = File('../../docs/brand/tokens.json');
  final t = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
  final color = t['color'] as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_theme.dart from docs/brand/tokens.json. Do not edit.')
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln();

  for (final mode in ['dark', 'light']) {
    final cls = mode == 'dark' ? 'DarkTokens' : 'LightTokens';
    b.writeln('abstract final class $cls {');
    (color[mode] as Map<String, dynamic>).forEach((k, v) {
      b.writeln('  static const Color $k = Color(${_hex(v as String)});');
    });
    b.writeln('}\n');
  }

  final btn = color['button'] as Map<String, dynamic>;
  b.writeln('abstract final class ButtonTokens {');
  b.writeln('  static const List<Color> primaryGradient = [');
  for (final c in btn['primaryGradient'] as List) {
    b.writeln('    Color(${_hex(c as String)}),');
  }
  b.writeln('  ];');
  b.writeln('  static const Color primaryText = Color(${_hex(btn['primaryText'] as String)});');
  b.writeln('  static const List<Color> wineGradient = [');
  for (final c in btn['wineGradient'] as List) {
    b.writeln('    Color(${_hex(c as String)}),');
  }
  b.writeln('  ];');
  b.writeln('}\n');

  final r = t['radius'] as Map<String, dynamic>;
  final c = t['component'] as Map<String, dynamic>;
  b.writeln('abstract final class SizeTokens {');
  for (final k in ['input', 'cardSmall', 'card', 'sheet', 'button']) {
    b.writeln('  static const double radius${k[0].toUpperCase()}${k.substring(1)} = ${r[k]};');
  }
  b.writeln('  static const double buttonHeight = ${c['buttonHeight']};');
  b.writeln('  static const double touchTargetMin = ${c['touchTargetMin']};');
  b.writeln('  static const double touchTargetCrew = ${c['touchTargetCrew']};');
  b.writeln('}');

  File('lib/core/ui/tokens.g.dart').writeAsStringSync(b.toString());
  stdout.writeln('wrote lib/core/ui/tokens.g.dart');
}
