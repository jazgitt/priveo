// Turns docs/brand/tokens.json into src/theme/tokens.g.css.
// Run from apps/web:  npm run theme
// `--check` fails when the file on disk is stale (used by `npm run lint`).
// The admin portal uses the light (cream) palette.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensPath = resolve(here, "../../../docs/brand/tokens.json");
const outPath = resolve(here, "../src/theme/tokens.g.css");

const t = JSON.parse(readFileSync(tokensPath, "utf8"));
const kebab = (k) => k.replace(/([A-Z])/g, "-$1").toLowerCase();
const stack = (f) => [f.family, ...f.fallback].map((n) => (n.includes(" ") ? `"${n}"` : n)).join(", ");

const lines = [
  "/* GENERATED by tools/gen-theme.mjs from docs/brand/tokens.json. Do not edit. */",
  ":root {",
];
for (const [k, v] of Object.entries(t.color.light)) lines.push(`  --c-${kebab(k)}: ${v};`);
const dark = t.color.dark;
for (const k of ["goldHi", "goldLo", "wineHi"]) lines.push(`  --c-${kebab(k)}: ${dark[k]};`);
lines.push(`  --c-gold-grad: linear-gradient(135deg, ${t.color.button.primaryGradient.join(", ")});`);
lines.push(`  --c-gold-text-on: ${t.color.button.primaryText};`);
lines.push(`  --c-wine-grad: linear-gradient(135deg, ${t.color.button.wineGradient.join(", ")});`);
for (const [k, v] of Object.entries(t.radius)) {
  lines.push(`  --r-${kebab(k)}: ${typeof v === "number" ? `${v}px` : v};`);
}
lines.push(`  --font-display: ${stack(t.font.display)};`);
lines.push(`  --font-body: ${stack(t.font.body)};`);
t.font.scale.forEach((s, i) => lines.push(`  --fs-${i + 1}: ${s / 16}rem;`));
lines.push(`  --touch-min: ${t.component.touchTargetMin}px;`);
lines.push(`  --motion-fast: ${t.component.motionMs[0]}ms;`);
lines.push(`  --motion: ${t.component.motionMs[1]}ms;`);
lines.push("}", "");
const css = lines.join("\n");

if (process.argv.includes("--check")) {
  // Line endings differ between Windows checkouts and CI. Compare without them.
  const current = existsSync(outPath)
    ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n")
    : "";
  if (current !== css) {
    console.error("src/theme/tokens.g.css is stale. Run: npm run theme");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, css);
  console.log("wrote src/theme/tokens.g.css");
}
